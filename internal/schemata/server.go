package schemata

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"path/filepath"
	"slices"
	"strconv"

	"github.com/ambi/gamut/internal/load"
)

// ServerTestName は、1 つのテストプロセスで変異体を順に判定する、overlay で足すテストの名前である。
const ServerTestName = "TestGamutServer"

// ServerFileName は、そのテストを置くファイルの名前である。
const ServerFileName = "gamut_server_test.go"

// Server は、1 つのテストプロセスで複数の変異体を順に判定するためのテストファイルである。
// 判定のテストは、標準入力から「変異体の番号 テスト名...」の行を受け取り、選択を切り替え、テストを t.Run で順に呼ぶ。
// 各テストを始める前に「run <名前>」を、終わったら「pass」か「fail <名前>」を、ファイル記述子 3 へ書く。
// 「cover テスト名...」の行は、変異なしでテストを順に実行して被覆を記録し、各テストの所要時間を「d <名前> <ナノ秒>」で書き、
// 最後に被覆の記録を止める。被覆を測ったプロセスを、そのまま変異体の判定に使い回すために使う。
type Server struct {
	// Path と Src は、overlay で足すファイルのパスと内容である。
	Path string
	Src  []byte
	// Tests は、判定のテストから呼べるテスト（func(*testing.T) の形のトップレベルのテスト）の名前である。
	// Example と Fuzz は t.Run で呼べないので含めない。
	Tests map[string]bool
}

// BuildServer は、pkg の判定のテストを作る。作れなければ（名前が衝突する、main パッケージに外部テストがあるなど）nil を返す。
// 判定のテストは外部テストのパッケージに置き、内部テストは対象パッケージの公開された関数として、外部テストはそのまま呼ぶ。
// main パッケージは外部テストから import できないので、内部テストのパッケージに置く。
func BuildServer(pkg *load.Package) (*Server, error) {
	fset := token.NewFileSet()
	type test struct {
		name     string
		external bool
	}
	var tests []test
	hasExternal := false
	for _, path := range pkg.TestFiles {
		if filepath.Base(path) == ServerFileName {
			return nil, nil
		}
		f, err := parser.ParseFile(fset, path, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		external := f.Name.Name != pkg.Name
		hasExternal = hasExternal || external
		for _, d := range f.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Recv != nil || fd.Body == nil {
				continue
			}
			if fd.Name.Name == ServerTestName {
				return nil, nil
			}
			if isTestName(fd.Name.Name) && takesT(fd) && fd.Name.Name[:4] == "Test" {
				tests = append(tests, test{fd.Name.Name, external})
			}
		}
	}
	internal := pkg.Name == "main"
	if internal && hasExternal {
		return nil, nil
	}
	var buf bytes.Buffer
	ref := func(t test) string {
		if internal || t.external {
			return t.name
		}
		return "gamutpkg." + t.name
	}
	set, stop := "GamutSetActive", "GamutCoverStop"
	pkgName := pkg.Name + "_test"
	imports := "\t\"bufio\"\n\t\"fmt\"\n\t\"os\"\n\t\"strconv\"\n\t\"strings\"\n\t\"testing\"\n\t\"time\"\n"
	if internal {
		pkgName = pkg.Name
	} else {
		imports += "\n\tgamutpkg " + strconv.Quote(pkg.ImportPath) + "\n"
		set, stop = "gamutpkg."+set, "gamutpkg."+stop
	}
	fmt.Fprintf(&buf, "// Code generated by gamut. DO NOT EDIT.\n\npackage %s\n\nimport (\n%s)\n\n", pkgName, imports)
	buf.WriteString("var gamutServed = map[string]func(*testing.T){\n")
	names := map[string]bool{}
	slices.SortFunc(tests, func(a, b test) int {
		if a.name < b.name {
			return -1
		}
		return 1
	})
	for _, t := range tests {
		fmt.Fprintf(&buf, "\t%q: %s,\n", t.name, ref(t))
		names[t.name] = true
	}
	fmt.Fprintf(&buf, `}

// %s は、GAMUT_SERVE が設定されたときだけ、標準入力の命令に従って変異体を順に判定する。
func %s(t *testing.T) {
	if os.Getenv("GAMUT_SERVE") == "" {
		t.Skip("run by gamut only")
	}
	out := os.NewFile(3, "gamut-results")
	in := bufio.NewScanner(os.Stdin)
	in.Buffer(make([]byte, 1<<20), 1<<26)
	for in.Scan() {
		fields := strings.Fields(in.Text())
		if len(fields) == 0 {
			continue
		}
		cover := fields[0] == "cover"
		n := 0
		if !cover {
			n, _ = strconv.Atoi(fields[0])
		}
		%s(n)
		result := "pass"
		for _, name := range fields[1:] {
			fn := gamutServed[name]
			fmt.Fprintln(out, "run "+name)
			start := time.Now()
			// 外側の t.Run は、並列のサブテストが終わるまで戻らない。
			if !t.Run("g", func(t *testing.T) { t.Run(name, fn) }) {
				result = "fail " + name
				break
			}
			if cover {
				fmt.Fprintf(out, "d %%s %%d\n", name, time.Since(start))
			}
		}
		if cover {
			%s()
		}
		fmt.Fprintln(out, result)
	}
}
`, ServerTestName, ServerTestName, set, stop)
	return &Server{Path: filepath.Join(pkg.Dir, ServerFileName), Src: buf.Bytes(), Tests: names}, nil
}

// takesT は、関数が引数を 1 つだけ取り、その型が *<何か>.T であるかを返す。
func takesT(fd *ast.FuncDecl) bool {
	params := fd.Type.Params.List
	if len(params) != 1 || len(params[0].Names) > 1 {
		return false
	}
	star, ok := params[0].Type.(*ast.StarExpr)
	if !ok {
		return false
	}
	sel, ok := star.X.(*ast.SelectorExpr)
	return ok && sel.Sel.Name == "T"
}
