// Package load finds the target packages with go list and builds their syntax trees and type information.
package load

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/ast"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"io"
	"maps"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
	"sync"
)

// HelperImports are the standard packages the schemata helper file imports.
var HelperImports = []string{"os", "runtime", "strconv", "strings", "sync", "sync/atomic"}

// Package is one package to mutate.
type Package struct {
	// Dir is the absolute path of the package directory.
	Dir string
	// ImportPath is the package's import path.
	ImportPath string
	// Name is the package name.
	Name string
	// ModuleDir is the absolute path of the root of the module containing the package.
	ModuleDir string
	// ModulePath is the module path.
	ModulePath string
	// Tags are the build tags passed to loading and building.
	Tags []string
	// HasTests reports whether the package has test files (external tests included).
	HasTests bool
	// TestFiles are the absolute paths of the test files (external tests included).
	TestFiles []string
	// Fset holds the positions of every syntax tree. Packages read by one Load share it.
	Fset *token.FileSet
	// Files are the files to mutate (excluding tests and generated files).
	Files []*File
	// Others are the remaining files of the package, not mutated but needed for type-checking.
	Others []*File
	// Types and Info are the result of checking Files and Others together.
	Types *types.Package
	Info  *types.Info
	// GoVersion is the go version in the module's go.mod (such as "1.27.4").
	GoVersion string
	// Direct reports whether go tool compile can compile this package directly.
	// It is false for packages with embedded or assembly files, which need extra configuration.
	Direct bool

	importer  types.Importer
	exports   map[string]string
	importMap map[string]string
}

// ImportConfig returns the contents for -importcfg of go tool compile, pointing at the dependencies' export data.
// It lets this package compile from rewritten source without the build cache.
func (p *Package) ImportConfig() string {
	var b strings.Builder
	for _, path := range slices.Sorted(maps.Keys(p.exports)) {
		if file := p.exports[path]; file != "" {
			fmt.Fprintf(&b, "packagefile %s=%s\n", path, file)
		}
	}
	for _, from := range slices.Sorted(maps.Keys(p.importMap)) {
		fmt.Fprintf(&b, "importmap %s=%s\n", from, p.importMap[from])
	}
	return b.String()
}

// File is one file of a package.
type File struct {
	// Path is the file's absolute path.
	Path string
	// Rel is the path relative to the module root, separated by /.
	Rel string
	// Src is the file's contents.
	Src []byte
	// AST is the file's syntax tree.
	AST *ast.File
}

type listedPackage struct {
	Dir          string
	ImportPath   string
	Name         string
	DepOnly      bool
	GoFiles      []string
	CgoFiles     []string
	TestGoFiles  []string
	XTestGoFiles []string
	ImportMap    map[string]string
	Imports      []string
	EmbedFiles   []string
	SFiles       []string
	Module       *struct {
		Path      string
		Dir       string
		GoVersion string
	}
	Error *struct{ Err string }
	// cgoGenerated are the absolute paths of files generated by cgo preprocessing, used only for type-checking.
	cgoGenerated []string
}

// Skipped is a package left out of loading because it cannot be judged, with the reason.
type Skipped struct {
	ImportPath string
	Reason     string
}

// Load loads the packages matching patterns under the build tags tags and type-checks them.
func Load(patterns []string, tags []string) ([]*Package, error) {
	pkgs, _, _, err := WithHint(patterns, tags, nil)
	return pkgs, err
}

// listFields are the fields loading takes from go list.
const listFields = "Dir,ImportPath,Name,DepOnly,GoFiles,CgoFiles,TestGoFiles,XTestGoFiles,ImportMap,Imports,EmbedFiles,SFiles,Module,Error"

// WithHint loads like Load and returns, as the hint for the next load, the import paths of packages whose export data type-checking needs.
//
// Export data is computed only for the target packages' dependencies. Running go list -export -deps per target
// would compile the just-edited target into the build cache, and nothing uses that result
// (the schemata binary recompiles from rewritten source). So the dependency list (without -export) and
// the export data of the hinted packages are computed in parallel, and only what the hint misses is computed afterwards.
// When the hint matches the previous one, the two go list runs overlap, so the wait is one run.
//
// Packages using cgo are type-checked with the files after cgo preprocessing (go list -compiled), and only files without import "C" are mutated.
// When preprocessing fails (no C compiler, for example), the package is skipped and the reason returned in skipped.
func WithHint(patterns, tags, hint []string) (pkgs []*Package, needed []string, skipped []Skipped, err error) {
	if len(patterns) == 0 {
		return nil, nil, nil, errors.New("no package patterns")
	}
	abs, err := AbsPatterns(patterns)
	if err != nil {
		return nil, nil, nil, err
	}
	runDir := strings.TrimSuffix(abs[0], filepath.FromSlash("/..."))
	exports := map[string]string{}
	var hinted sync.WaitGroup
	var hintErr error
	if len(hint) > 0 {
		hinted.Go(func() { hintErr = listExports(runDir, tags, hint, exports) })
	}
	// The packages the schemata helper file imports are listed too, for type-checking.
	args := []string{"list", "-e", "-json=" + listFields, "-deps"}
	if len(tags) > 0 {
		args = append(args, "-tags="+strings.Join(tags, ","))
	}
	args = append(append(args, abs...), HelperImports...)
	out, err := goList(runDir, args)
	hinted.Wait()
	if err != nil {
		return nil, nil, nil, err
	}
	var targets []*listedPackage
	var all []*listedPackage
	dec := json.NewDecoder(bytes.NewReader(out))
	for {
		var p listedPackage
		if err := dec.Decode(&p); errors.Is(err, io.EOF) {
			break
		} else if err != nil {
			return nil, nil, nil, fmt.Errorf("decode go list output: %w", err)
		}
		if p.Error != nil {
			return nil, nil, nil, fmt.Errorf("go list %s: %s", p.ImportPath, p.Error.Err)
		}
		all = append(all, &p)
		if !p.DepOnly && !slices.Contains(HelperImports, p.ImportPath) && len(p.GoFiles)+len(p.CgoFiles) > 0 {
			targets = append(targets, &p)
		}
	}
	if len(targets) == 0 {
		return nil, nil, nil, fmt.Errorf("no packages with non-test Go files match %s", strings.Join(patterns, " "))
	}
	slices.SortFunc(targets, func(a, b *listedPackage) int { return strings.Compare(a.ImportPath, b.ImportPath) })

	// Export data is needed for everything but the targets, and for targets that another target imports.
	isTarget := map[string]bool{}
	for _, t := range targets {
		isTarget[t.ImportPath] = true
	}
	imported := map[string]bool{}
	for _, t := range targets {
		for _, path := range t.Imports {
			if mapped, ok := t.ImportMap[path]; ok {
				path = mapped
			}
			imported[path] = true
		}
	}
	var missing []string
	for _, p := range all {
		if isTarget[p.ImportPath] && !imported[p.ImportPath] || p.ImportPath == "unsafe" {
			continue
		}
		needed = append(needed, p.ImportPath)
		if hintErr != nil || exports[p.ImportPath] == "" {
			missing = append(missing, p.ImportPath)
		}
	}
	if len(missing) > 0 {
		if err := listExports(runDir, tags, missing, exports); err != nil {
			return nil, nil, nil, err
		}
	}
	fset := token.NewFileSet()
	shared := &sharedImporter{exports: exports}
	shared.imp = importer.ForCompiler(fset, "gc", shared.lookup)
	var cgoPaths []string
	for _, t := range targets {
		if len(t.CgoFiles) > 0 {
			cgoPaths = append(cgoPaths, t.ImportPath)
		}
	}
	compiled, err := listCompiled(runDir, tags, cgoPaths)
	if err != nil {
		return nil, nil, nil, err
	}
	for _, target := range targets {
		if len(target.CgoFiles) > 0 {
			target.cgoGenerated = generatedFiles(target, compiled[target.ImportPath])
			if len(target.cgoGenerated) == 0 {
				skipped = append(skipped, Skipped{ImportPath: target.ImportPath, Reason: "cgo preprocessing failed; is a C compiler (go env CC) available?"})
				continue
			}
		}
		if target.Module == nil {
			return nil, nil, nil, fmt.Errorf("package %s is not in a module", target.ImportPath)
		}
		if len(pkgs) > 0 && pkgs[0].ModuleDir != target.Module.Dir {
			// File paths in reports are module-relative, so they cannot be told apart across modules.
			return nil, nil, nil, fmt.Errorf("packages %s and %s are in different modules; run gamut once per module",
				pkgs[0].ImportPath, target.ImportPath)
		}
		pkg, err := newPackage(target, tags, fset, &packageImporter{shared: shared, importMap: target.ImportMap})
		if err != nil {
			return nil, nil, nil, err
		}
		pkg.exports, pkg.importMap = exports, target.ImportMap
		pkgs = append(pkgs, pkg)
	}
	if len(pkgs) == 0 {
		return nil, nil, skipped, fmt.Errorf("no package to judge: %s skipped (%s)", skipped[0].ImportPath, skipped[0].Reason)
	}
	return pkgs, needed, skipped, nil
}

// listCompiled finds the files after cgo preprocessing (CompiledGoFiles) of the packages paths.
// A package whose preprocessing fails gets an empty list.
func listCompiled(dir string, tags, paths []string) (map[string][]string, error) {
	if len(paths) == 0 {
		return nil, nil
	}
	args := []string{"list", "-e", "-compiled", "-json=ImportPath,CompiledGoFiles"}
	if len(tags) > 0 {
		args = append(args, "-tags="+strings.Join(tags, ","))
	}
	out, err := goList(dir, append(args, paths...))
	if err != nil {
		return nil, err
	}
	compiled := map[string][]string{}
	dec := json.NewDecoder(bytes.NewReader(out))
	for {
		var p struct {
			ImportPath      string
			CompiledGoFiles []string
		}
		if err := dec.Decode(&p); errors.Is(err, io.EOF) {
			break
		} else if err != nil {
			return nil, fmt.Errorf("decode go list output: %w", err)
		}
		compiled[p.ImportPath] = p.CompiledGoFiles
	}
	return compiled, nil
}

// generatedFiles returns the absolute paths of the files in CompiledGoFiles that cgo generated (those not in GoFiles).
func generatedFiles(target *listedPackage, compiled []string) []string {
	var out []string
	for _, f := range compiled {
		if !filepath.IsAbs(f) {
			f = filepath.Join(target.Dir, f)
		}
		if filepath.Dir(f) == target.Dir && slices.Contains(target.GoFiles, filepath.Base(f)) {
			continue
		}
		out = append(out, f)
	}
	return out
}

// goList runs go with args in dir and returns stdout.
func goList(dir string, args []string) ([]byte, error) {
	cmd := exec.Command("go", args...)
	cmd.Dir = dir
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list in %s: %w: %s", dir, err, strings.TrimSpace(stderr.String()))
	}
	return out, nil
}

// listExports finds the export data files of the packages paths and adds them to exports.
// Packages it cannot find (such as removed ones) are not added.
func listExports(dir string, tags, paths []string, exports map[string]string) error {
	args := []string{"list", "-e", "-export", "-json=ImportPath,Export"}
	if len(tags) > 0 {
		args = append(args, "-tags="+strings.Join(tags, ","))
	}
	out, err := goList(dir, append(args, paths...))
	if err != nil {
		return err
	}
	found := map[string]string{}
	dec := json.NewDecoder(bytes.NewReader(out))
	for {
		var p struct{ ImportPath, Export string }
		if err := dec.Decode(&p); errors.Is(err, io.EOF) {
			break
		} else if err != nil {
			return fmt.Errorf("decode go list output: %w", err)
		}
		if p.Export != "" {
			found[p.ImportPath] = p.Export
		}
	}
	maps.Copy(exports, found)
	return nil
}

func newPackage(target *listedPackage, tags []string, fset *token.FileSet, imp types.Importer) (*Package, error) {
	pkg := &Package{
		Dir:        target.Dir,
		ImportPath: target.ImportPath,
		Name:       target.Name,
		ModuleDir:  target.Module.Dir,
		ModulePath: target.Module.Path,
		Tags:       tags,
		HasTests:   len(target.TestGoFiles)+len(target.XTestGoFiles) > 0,
		Fset:       fset,
		GoVersion:  target.Module.GoVersion,
		// cgo packages need cgo's outputs passed to go tool compile, so they are not compiled directly.
		Direct:   len(target.EmbedFiles) == 0 && len(target.SFiles) == 0 && len(target.CgoFiles) == 0,
		importer: imp,
	}
	for _, name := range slices.Concat(target.TestGoFiles, target.XTestGoFiles) {
		pkg.TestFiles = append(pkg.TestFiles, filepath.Join(target.Dir, name))
	}
	for _, name := range target.GoFiles {
		path := filepath.Join(target.Dir, name)
		src, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		f, err := parser.ParseFile(pkg.Fset, path, src, parser.ParseComments|parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		rel, err := filepath.Rel(pkg.ModuleDir, path)
		if err != nil {
			return nil, err
		}
		file := &File{Path: path, Rel: filepath.ToSlash(rel), Src: src, AST: f}
		if ast.IsGenerated(f) {
			pkg.Others = append(pkg.Others, file)
		} else {
			pkg.Files = append(pkg.Files, file)
		}
	}
	// Files cgo generated (the preprocessed files with import "C" and the Go side of the C declarations) are used only for type-checking and never mutated.
	for _, path := range target.cgoGenerated {
		src, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		f, err := parser.ParseFile(pkg.Fset, path, src, parser.ParseComments|parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		pkg.Others = append(pkg.Others, &File{Path: path, Rel: filepath.Base(path), Src: src, AST: f})
	}
	info := NewInfo()
	tpkg, errs := pkg.Check(pkg.Fset, pkg.AllASTs(), info)
	if len(errs) > 0 {
		return nil, fmt.Errorf("type-check %s: %w", pkg.ImportPath, errs[0])
	}
	pkg.Types = tpkg
	pkg.Info = info
	return pkg, nil
}

// sharedImporter shares the types.Package read from export data among all target packages.
// The gc importer is not safe for concurrent use, so a mutex guards it.
// A target importing another target also reads the export data from before the rewrite.
type sharedImporter struct {
	mu      sync.Mutex
	imp     types.Importer
	exports map[string]string
	// importMap points at the importing package's ImportMap, only during a call holding mu.
	importMap map[string]string
}

func (s *sharedImporter) lookup(path string) (io.ReadCloser, error) {
	if mapped, ok := s.importMap[path]; ok {
		path = mapped
	}
	export, ok := s.exports[path]
	if !ok || export == "" {
		return nil, fmt.Errorf("no export data for %s", path)
	}
	return os.Open(export)
}

// packageImporter looks up the shared importer through one target package's ImportMap.
type packageImporter struct {
	shared    *sharedImporter
	importMap map[string]string
}

func (p *packageImporter) Import(path string) (*types.Package, error) {
	p.shared.mu.Lock()
	defer p.shared.mu.Unlock()
	p.shared.importMap = p.importMap
	return p.shared.imp.Import(path)
}

// AbsPatterns makes the directories of patterns absolute, keeping the <directory>/... form.
func AbsPatterns(patterns []string) ([]string, error) {
	var abs []string
	for _, p := range patterns {
		dir, rest := p, ""
		if d, ok := strings.CutSuffix(filepath.ToSlash(p), "/..."); ok {
			dir, rest = filepath.FromSlash(d), "/..."
		} else if p == "..." {
			dir, rest = ".", "/..."
		}
		a, err := filepath.Abs(dir)
		if err != nil {
			return nil, err
		}
		abs = append(abs, a+filepath.FromSlash(rest))
	}
	return abs, nil
}

// ModuleRoot returns the first directory with a go.mod walking up from dir, or empty when there is none.
func ModuleRoot(dir string) string {
	for d := dir; ; d = filepath.Dir(d) {
		if _, err := os.Stat(filepath.Join(d, "go.mod")); err == nil {
			return d
		}
		if filepath.Dir(d) == d {
			return ""
		}
	}
}

// NewInfo creates the type information holder that enumeration and rewriting refer to.
func NewInfo() *types.Info {
	return &types.Info{
		Types: map[ast.Expr]types.TypeAndValue{},
		Uses:  map[*ast.Ident]types.Object{},
		Defs:  map[*ast.Ident]types.Object{},
	}
}

// AllASTs returns the syntax trees of the target and other files in their original order.
func (p *Package) AllASTs() []*ast.File {
	files := make([]*ast.File, 0, len(p.Files)+len(p.Others))
	for _, f := range p.Files {
		files = append(files, f.AST)
	}
	for _, f := range p.Others {
		files = append(files, f.AST)
	}
	return files
}

// Check type-checks files, which belong to fset, as this package and returns every error.
// When info is nil, no type information is recorded.
func (p *Package) Check(fset *token.FileSet, files []*ast.File, info *types.Info) (*types.Package, []types.Error) {
	var errs []types.Error
	conf := types.Config{
		Importer: p.importer,
		Error: func(err error) {
			if terr, ok := errors.AsType[types.Error](err); ok {
				errs = append(errs, terr)
			}
		},
	}
	tpkg, _ := conf.Check(p.ImportPath, fset, files, info)
	return tpkg, errs
}
